import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {transform} from 'esbuild';
const {code}=await transform(await fs.readFile(new URL('../src/progress.ts',import.meta.url),'utf8'),{loader:'ts',format:'esm',target:'es2022'});
const {RecentRate,jobProgressText,submittedJobText}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const job={id:'a',started:1,status:'running',done:26000,succeeded:25000,elapsed_s:58000};
const rate=new RecentRate();
assert.equal(rate.sample(job,0),null);
assert.equal(rate.sample({...job,succeeded:25004},4000),null);
assert.equal(rate.sample({...job,succeeded:25030,done:26100},30000),1,'skips and historical elapsed time do not inflate or depress throughput');
assert.equal(rate.sample({...job,succeeded:25030},60000),0,'waiting contributes to real throughput');
assert.equal(rate.sample({...job,status:'paused'},61000),null);
assert.equal(rate.sample({...job,succeeded:25030,started:2},62000),null);
assert.equal(rate.sample({...job,succeeded:25040,started:2},72000),1,'resume starts a fresh sample');
assert.equal(rate.sample({...job,succeeded:25040,started:2},140000),null,'long background gap resets measurement');
assert.equal(rate.sample({...job,succeeded:1,started:2},141000),null,'retry/reset cannot produce a negative speed');
assert.equal(rate.sample({...job,id:'b'},142000),null,'new job cannot inherit previous rate');
assert.equal(rate.sample({...job,id:'b',succeeded:25010},152000),1);
console.log('PASS recent throughput: warmup, rolling window, skipped tasks, waiting, pause/resume, long gaps, resets, new jobs');
const state={...job,action:'archive',total:10,done:3,succeeded:3,workers:4,running:['a','b']};
assert.equal(jobProgressText(state,2,null),'圧縮・保管 3/10 · 2/4並列 · 速度計測中 · 待ち 2件');
assert.equal(jobProgressText(state,0,1.25),'圧縮・保管 3/10 · 2/4並列 · 直近 1.3枚/秒');
assert.match(jobProgressText({...state,wait_reason:'CPU待機'},0,1),/CPU待機$/);
assert.match(jobProgressText({...state,stopping:true,wait_reason:'CPU待機'},0,1),/処理中の画像が終わったら一時停止$/);
for(const status of ['paused','cancelled'])assert.equal(jobProgressText({...state,status},0,null),'一時停止 · 3/10件処理済み');
assert.equal(jobProgressText({...state,status:'error',message:'disk full'},0,null),'処理停止 · disk full');
assert.equal(jobProgressText({...state,status:'error'},0,null),'処理停止 · 処理履歴を確認してください');
assert.equal(jobProgressText({...state,status:'done',skipped:4,not_smaller:2,error_count:1},0,null),'3件完了 · 原本保持 2件（削減なし） · 2件スキップ · 1件失敗');
assert.equal(submittedJobText({...state,status:'queued'}),'圧縮・保管 10件を待ち行列に追加');
assert.equal(submittedJobText(state),'圧縮・保管 3/10');
console.log('PASS progress labels: running, queue, waiting, stopping, paused, errors, retained originals, skipped tasks, submitted jobs');
